"""Classical post-processing module for BB84: Error Reconciliation & Privacy Amplification.

Implements:
1. Cascade-Lite Parity Error Correction: Blocks keys and corrects mismatches
   via parity checks and binary search bisection.
2. Privacy Amplification: Distills raw keys into secure, uniformly distributed
   secret keys via cryptographic hashing (SHA-256) sized according to the
   Shor-Preskill mutual information bound.
3. One-Time Pad (OTP) Message Encryption & Decryption for end-to-end demonstrations.
"""

from __future__ import annotations

import hashlib
import math
from typing import List, Tuple
import numpy as np

from bb84.analysis import binary_entropy


def reconcile_errors_parity(
    alice_key: np.ndarray,
    bob_key: np.ndarray,
    block_size: int = 8,
) -> Tuple[np.ndarray, np.ndarray, int]:
    """Perform simple block-parity error correction (Cascade-Lite).

    Divides the keys into blocks of size `block_size`. For blocks where
    parities differ, uses bisection search to pinpoint and flip the mismatched
    bit in Bob's key.

    Args:
        alice_key: Alice's raw key bits (numpy array of 0s and 1s).
        bob_key: Bob's raw key bits.
        block_size: Block size for parity checks (default 8).

    Returns:
        Tuple of (reconciled_alice_key, reconciled_bob_key, num_corrections).
    """
    if len(alice_key) == 0 or len(bob_key) == 0:
        return alice_key, bob_key, 0

    corrected_bob = bob_key.copy()
    num_corrections = 0
    n = min(len(alice_key), len(corrected_bob))

    for start in range(0, n, block_size):
        end = min(start + block_size, n)
        a_blk = alice_key[start:end]
        b_blk = corrected_bob[start:end]

        # Parity check: sum mod 2
        p_a = int(np.sum(a_blk) % 2)
        p_b = int(np.sum(b_blk) % 2)

        if p_a != p_b:
            # Binary search to find single mismatched bit in block
            low = start
            high = end
            while high - low > 1:
                mid = (low + high) // 2
                sub_a_p = int(np.sum(alice_key[low:mid]) % 2)
                sub_b_p = int(np.sum(corrected_bob[low:mid]) % 2)
                if sub_a_p != sub_b_p:
                    high = mid
                else:
                    low = mid
            # Flip the identified bit in Bob's key
            corrected_bob[low] = 1 - corrected_bob[low]
            num_corrections += 1

    return alice_key[:n], corrected_bob[:n], num_corrections


def amplify_privacy(
    raw_key: np.ndarray,
    estimated_qber: float,
    salt: bytes = b"EveWatch_QKD_2026",
) -> np.ndarray:
    """Perform privacy amplification to remove leaked information using SHA-256.

    Shor-Preskill theorem bounds the extractable fraction of secret bits as
    R = max(0, 1 - 2*H2(QBER)).
    The final secret key is generated by hashing the reconciled key with SHA-256
    and truncating to the secure length.

    Args:
        raw_key: Reconciled key bits (numpy array of 0s and 1s).
        estimated_qber: Estimated channel/attack QBER in [0, 0.5].
        salt: Domain separation salt for hashing.

    Returns:
        Compressed, information-theoretically secure key bit array.
    """
    n_raw = len(raw_key)
    if n_raw == 0:
        return np.array([], dtype=np.int32)

    h2 = binary_entropy(estimated_qber)
    fraction = max(0.0, 1.0 - 2.0 * h2)
    target_length = int(math.floor(n_raw * fraction))

    if target_length <= 0:
        return np.array([], dtype=np.int32)

    # Convert bit array to byte string
    bitstring = "".join(str(int(b)) for b in raw_key)
    hasher = hashlib.sha256()
    hasher.update(salt)
    hasher.update(bitstring.encode("utf-8"))
    digest = hasher.digest()

    # Expand or truncate hash bytes into target bit array
    # If target_length > 256 bits, chain hashing (HKDF-like)
    derived_bits: List[int] = []
    counter = 0
    while len(derived_bits) < target_length:
        block_hasher = hashlib.sha256()
        block_hasher.update(digest)
        block_hasher.update(counter.to_bytes(4, byteorder="big"))
        block_bytes = block_hasher.digest()
        for byte_val in block_bytes:
            for shift in range(7, -1, -1):
                derived_bits.append((byte_val >> shift) & 1)
                if len(derived_bits) >= target_length:
                    break
            if len(derived_bits) >= target_length:
                break
        counter += 1

    return np.array(derived_bits[:target_length], dtype=np.int32)


def encrypt_message_otp(message: str, key_bits: np.ndarray) -> Tuple[str, str]:
    """Encrypt a plaintext string using One-Time Pad (XOR) with a key bit array.

    Args:
        message: Plaintext UTF-8 string.
        key_bits: Binary key array of 0s and 1s.

    Returns:
        Tuple of (ciphertext_hex, ciphertext_binary_str).
    """
    if len(key_bits) == 0:
        return "", ""

    msg_bytes = message.encode("utf-8")
    msg_bits: List[int] = []
    for b in msg_bytes:
        for shift in range(7, -1, -1):
            msg_bits.append((b >> shift) & 1)

    # Stream cipher XOR: recycle or repeat key if necessary
    k_len = len(key_bits)
    cipher_bits = [(msg_bits[i] ^ int(key_bits[i % k_len])) for i in range(len(msg_bits))]

    # Convert to hex representation
    cipher_bytes = bytearray()
    for i in range(0, len(cipher_bits), 8):
        byte_chunk = cipher_bits[i : i + 8]
        val = 0
        for bit in byte_chunk:
            val = (val << 1) | bit
        if len(byte_chunk) < 8:
            val = val << (8 - len(byte_chunk))
        cipher_bytes.append(val)

    hex_str = cipher_bytes.hex().upper()
    bin_str = "".join(str(b) for b in cipher_bits[:64]) + ("..." if len(cipher_bits) > 64 else "")
    return hex_str, bin_str


def decrypt_message_otp(hex_ciphertext: str, key_bits: np.ndarray) -> str:
    """Decrypt a hex ciphertext string using One-Time Pad (XOR) with key bits.

    Args:
        hex_ciphertext: Hex string representing ciphertext bytes.
        key_bits: Binary key array of 0s and 1s.

    Returns:
        Decrypted UTF-8 plaintext string.
    """
    if len(key_bits) == 0 or not hex_ciphertext:
        return ""

    try:
        cipher_bytes = bytes.fromhex(hex_ciphertext)
    except ValueError:
        return "[Decryption Error: Invalid hex ciphertext]"

    cipher_bits: List[int] = []
    for b in cipher_bytes:
        for shift in range(7, -1, -1):
            cipher_bits.append((b >> shift) & 1)

    k_len = len(key_bits)
    plain_bits = [(cipher_bits[i] ^ int(key_bits[i % k_len])) for i in range(len(cipher_bits))]

    plain_bytes = bytearray()
    for i in range(0, len(plain_bits), 8):
        byte_chunk = plain_bits[i : i + 8]
        if len(byte_chunk) == 8:
            val = 0
            for bit in byte_chunk:
                val = (val << 1) | bit
            plain_bytes.append(val)

    try:
        return plain_bytes.decode("utf-8", errors="replace")
    except Exception as exc:
        return f"[Decryption Error: {exc}]"
